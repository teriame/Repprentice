#!/usr/bin/env python3
"""
Embeds the Python recompiler / CHD tools, runtime/recomp.h, and game.json into
a single C header (embedded_tools.h) so the final Windows .exe and Linux
AppImage binary are 100% self-contained and require no external files.
"""
import os
import sys

FILES = [
    ("tools/chd.py", "tools/chd.py"),
    ("tools/cdi_extract.py", "tools/cdi_extract.py"),
    ("tools/m68k.py", "tools/m68k.py"),
    ("tools/os9mod.py", "tools/os9mod.py"),
    ("tools/analyze.py", "tools/analyze.py"),
    ("tools/config.py", "tools/config.py"),
    ("tools/gen.py", "tools/gen.py"),
    ("runtime/recomp.h", "runtime/recomp.h"),
    ("game.json", "game.json"),
]


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "build", "embedded_tools.h")
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)

    lines = [
        "/* Auto-generated by tools/embed_tools.py - DO NOT EDIT */",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const char *rel_path;",
        "    const uint8_t *data;",
        "    size_t size;",
        "} EmbeddedToolFile;",
        "",
    ]

    entries = []
    for idx, (rel_src, rel_dst) in enumerate(FILES):
        full = os.path.join(root, rel_src)
        with open(full, "rb") as f:
            raw = f.read()
        var = f"emb_file_{idx}"
        hex_bytes = ", ".join(f"0x{b:02x}" for b in raw)
        lines.append(f"static const uint8_t {var}[{len(raw) + 1}] = {{ {hex_bytes}, 0x00 }};")
        entries.append((rel_dst, var, len(raw)))

    lines.append("")
    lines.append("static const EmbeddedToolFile embedded_tool_files[] = {")
    for rel_dst, var, sz in entries:
        lines.append(f'    {{ "{rel_dst}", {var}, {sz}u }},')
    lines.append("    { NULL, NULL, 0 }")
    lines.append("};")
    lines.append("")

    content = "\n".join(lines)
    if os.path.isfile(out_path):
        try:
            with open(out_path, "r", encoding="utf-8") as f:
                if f.read() == content:
                    return
        except Exception:
            pass
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)


if __name__ == "__main__":
    main()
